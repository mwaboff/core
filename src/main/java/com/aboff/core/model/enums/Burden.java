package com.aboff.core.model.enums;

/**
 * Represents the burden type of a weapon in Daggerheart.
 * Indicates how many hands are required to wield the weapon effectively.
 */
public enum Burden {
    /**
     * Weapon can be wielded with one hand, allowing use of a shield or off-hand weapon.
     */
    ONE_HANDED,

    /**
     * Weapon requires both hands to wield effectively.
     */
    TWO_HANDED
}
