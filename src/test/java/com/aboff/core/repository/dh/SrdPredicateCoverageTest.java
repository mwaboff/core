/**
 * Structural guard for SRD content gating: every repository {@code @Query} whose FROM clause
 * names a gated entity must bind {@code :includeNonSrd}, or be explicitly allowlisted with a
 * real reason.
 * <p>
 * This does not verify the predicate is <em>correct</em> — only that it exists. Its job is to
 * make it impossible to ship a new (or modified) catalogue query against a gated entity that
 * silently omits SRD gating, across the roughly twenty repositories and one hundred-plus
 * {@code @Query} methods in {@code repository.dh}, without anyone having to remember to check.
 * </p>
 * <p>
 * The scan walks {@code repository.dh}'s compiled classes directly rather than going through
 * Spring's {@code ClassPathScanningCandidateComponentProvider} — that provider's default
 * candidate filter excludes interfaces (it requires {@code isConcrete()}), which is exactly
 * everything in this package, and working around that filter is more fragile than reading the
 * classpath directory. {@link #testFewerThan20RepositoriesMeansTheScanIsBroken()} exists so a
 * scan that silently finds nothing can never masquerade as a passing test.
 * </p>
 */
