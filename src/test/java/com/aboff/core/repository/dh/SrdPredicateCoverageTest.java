    @Test
    void testFewerThan20RepositoriesMeansTheScanIsBroken() {
        List<Class<?>> repositories = scanRepositoryInterfaces();

        assertThat(repositories.size())
                .as("repository.dh scan found %d interfaces; expected at least 20. "
                        + "A broken scan (e.g. a wrong classpath directory) must fail loudly rather "
                        + "than silently pass with zero repositories checked.", repositories.size())
                .isGreaterThanOrEqualTo(20);
    }

    @Test
    void everyGatedQueryBindsIncludeNonSrdOrIsExplicitlyAllowlisted() {
        List<Class<?>> repositories = scanRepositoryInterfaces();
        List<String> offenders = new ArrayList<>();

        for (Class<?> repository : repositories) {
            for (Method method : repository.getDeclaredMethods()) {
                Query query = method.getAnnotation(Query.class);
                if (query == null) {
                    continue;
                }

                if (!namesGatedEntity(query.value()) && !namesGatedEntity(query.countQuery())) {
                    continue;
                }

                boolean bindsIncludeNonSrd = query.value().contains(":includeNonSrd")
                        || query.countQuery().contains(":includeNonSrd");
                if (bindsIncludeNonSrd) {
                    continue;
                }

                String key = repository.getSimpleName() + "#" + method.getName();
                if (!ALLOWED_UNGATED_QUERIES.containsKey(key)) {
                    offenders.add(key);
                }
            }
        }

        if (!offenders.isEmpty()) {
            fail(describeOffenders(offenders));
        }
    }

    /**
     * Returns true if the given JPQL string's FROM clause names one of {@link #GATED_ENTITIES}.
     * A blank or null string (as {@code countQuery()} is when unset) names nothing.
     *
     * @param jpql the query text to inspect; may be null or blank
     * @return true if a gated entity appears immediately after a {@code FROM} keyword
     */
    private boolean namesGatedEntity(String jpql) {
        if (jpql == null || jpql.isBlank()) {
            return false;
        }
        Matcher matcher = FROM_ENTITY_PATTERN.matcher(jpql);
        while (matcher.find()) {
            if (GATED_ENTITIES.contains(matcher.group(1))) {
                return true;
            }
        }
        return false;
    }

    /**
     * Loads every {@code interface} in {@link #REPOSITORY_PACKAGE} that implements Spring
     * Data's {@link Repository} marker, by reading the compiled {@code .class} files from the
     * test classpath directly.
     * <p>
     * Deliberately not {@code ClassPathScanningCandidateComponentProvider}: its default
     * candidate filter requires {@code isConcrete()}, which excludes every interface in this
     * package outright, and overriding that filter is more fragile than a directory listing.
     * </p>
     * <p>
     * Uses {@code getResources} (plural), not {@code getResource}: this test class lives in the
     * same package it scans ({@code com.aboff.core.repository.dh}), under {@code test-classes}
     * rather than {@code classes}. Both directories match the package path and both are on the
     * classpath, so the singular, first-match {@code getResource} can resolve to
     * {@code test-classes}' copy of the package — which contains only this test class — and
     * silently miss every real repository in {@code target/classes}. Merging every matching
     * directory sidesteps that classpath-ordering trap entirely.
     * </p>
     *
     * @return the repository interfaces found; never null, possibly empty if the scan itself
     *         is broken (see {@link #testFewerThan20RepositoriesMeansTheScanIsBroken()})
     */
    private List<Class<?>> scanRepositoryInterfaces() {
        String packagePath = REPOSITORY_PACKAGE.replace('.', '/');
        List<Class<?>> repositories = new ArrayList<>();

        try {
            Enumeration<URL> packageUrls = Thread.currentThread().getContextClassLoader().getResources(packagePath);
            while (packageUrls.hasMoreElements()) {
                repositories.addAll(loadRepositoriesFrom(packageUrls.nextElement()));
            }
        } catch (IOException e) {
            throw new IllegalStateException("Failed to enumerate classpath resources for " + packagePath, e);
        }

        return repositories;
    }

    /**
     * Loads every {@link Repository} interface whose compiled {@code .class} file sits directly
     * in the given package directory.
     *
     * @param packageDirUrl a {@code file:} URL for one classpath entry's copy of the package
     *                      directory
     * @return the repository interfaces found in that directory; empty if none
     */
    private List<Class<?>> loadRepositoriesFrom(URL packageDirUrl) {
        File packageDir = new File(packageDirUrl.getFile());
        File[] classFiles = packageDir.listFiles((dir, name) -> name.endsWith(".class"));
        if (classFiles == null) {
            return List.of();
        }

        List<Class<?>> repositories = new ArrayList<>();
        for (File classFile : classFiles) {
            String simpleName = classFile.getName().substring(0, classFile.getName().length() - ".class".length());
            String className = REPOSITORY_PACKAGE + "." + simpleName;
            try {
                Class<?> candidate = Class.forName(className);
                if (candidate.isInterface() && Repository.class.isAssignableFrom(candidate)) {
                    repositories.add(candidate);
                }
            } catch (ClassNotFoundException e) {
                throw new IllegalStateException("Failed to load scanned class: " + className, e);
            }
        }
        return repositories;
    }

    /**
     * Formats the offending method list for a clear, actionable test failure message.
     *
     * @param offenders the "RepositoryInterface#methodName" keys that failed the check
     * @return a multi-line failure message listing every offender
     */
    private String describeOffenders(List<String> offenders) {
        StringBuilder message = new StringBuilder();
        message.append(offenders.size())
                .append(offenders.size() == 1 ? " query names" : " queries name")
                .append(" a gated entity in its FROM clause but neither binds :includeNonSrd nor")
                .append(" appears in ALLOWED_UNGATED_QUERIES:\n");
        offenders.stream().sorted().forEach(offender -> message.append("  - ").append(offender).append('\n'));
        message.append("Fix: add the :includeNonSrd predicate to the query, or add a real reason to ")
                .append("ALLOWED_UNGATED_QUERIES in ").append(SrdPredicateCoverageTest.class.getSimpleName())
                .append('.');
        return message.toString();
    }
